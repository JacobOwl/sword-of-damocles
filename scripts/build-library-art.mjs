// Copies the art library's pictures that the game uses (assets/library) into the game's code:
//   ui/components/library-scenes.ts  the 39 event pictures drawn for the library, merged into VIGNETTES, so events in
//                                    data/ can name them with "art";
//   ui/components/library-pictures.ts  standalone pictures the screens show (faces for Carthage's council, Carthage's
//                                    coin), as data URLs.
// The library stays the one source of these drawings; rerun this after changing them (and after
// node assets/library/tools/build-made.mjs). Safe to rerun: same input, same output.
// Run from the repo root:  node scripts/build-library-art.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { NEW_TONDOS } from "../assets/library/tools/lib/tondos.mjs";

const scenes = NEW_TONDOS.map((t) => `  ${JSON.stringify(t.id)}: ${JSON.stringify(t.body.replace(/\s*\n\s*/g, " "))},`);
writeFileSync("ui/components/library-scenes.ts", `// GENERATED by scripts/build-library-art.mjs from assets/library/tools/lib/tondos.mjs. Do not edit by hand.
// The art library's event pictures, merged into VIGNETTES (ui/components/vignettes.ts). All of it is invention.
export const LIBRARY_SCENES: Record<string, string> = {
${scenes.join("\n")}
};
`);

// Which library files the screens use, by the key the screens ask for.
const PICTURES = {
  "face:himilcon": "made/medallions/himilcon.svg",
  "face:magon": "made/medallions/magon.svg",
  "face:hanno": "made/medallions/hanno.svg",
  "face:bomilcar": "made/medallions/bomilcar.svg",
  "coin:carthage": "made/coins/carthage-horse.svg",
};
const url = (file) => {
  const svg = readFileSync(`assets/library/${file}`, "utf8").replace(/<\?xml[^>]*>\s*/, "").replace(/\s*\n\s*/g, " ").trim();
  return "data:image/svg+xml," + encodeURIComponent(svg).replace(/%20/g, " ").replace(/%3D/g, "=").replace(/%3A/g, ":").replace(/%2F/g, "/");
};
const pics = Object.entries(PICTURES).map(([k, f]) => `  ${JSON.stringify(k)}: ${JSON.stringify(url(f))},`);
writeFileSync("ui/components/library-pictures.ts", `// GENERATED by scripts/build-library-art.mjs from files in assets/library/made/. Do not edit by hand.
// Pictures from the art library that the screens show, as data URLs. The faces and the drawing are invention.
export const LIBRARY_PICTURES: Record<string, string> = {
${pics.join("\n")}
};
`);
console.log(`wrote ${NEW_TONDOS.length} scenes and ${pics.length} pictures`);
